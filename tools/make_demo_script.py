"""Generate DEMO_VIDEO.md: a ~3-minute narrated website demo that follows the pitch deck.

Every number is read from the exported data the website uses (web/public/data/*.json), so the script
stays in step with the model (AGENTS.md rule 1). Run: python tools/make_demo_script.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "web/public/data"
load = lambda f: json.loads((D / f).read_text())  # noqa: E731


def k(x: float, d: int = 0) -> str:
    return f"{x / 1000:,.{d}f}K"


def num(x: float) -> str:
    v = round(x)
    return f"{v:,}" if v != 0 else "0"


def main() -> None:
    c, r, s, ev = load("constants.json"), load("results.json"), load("strategy.json"), load("events.json")
    t1 = {x["cond"]: x for x in r["t1"]}
    sens = {x["tag"]: x for x in r["sens"]}
    dec = {x["component"].split(" ")[0]: x["mean"] for x in r["dec"]}
    val = lambda tag: sens[tag]["v1"] + sens[tag]["v2"]  # noqa: E731
    base_val = dec["V1"] + dec["V2"]
    annual = sorted([e for e in ev if e["is_annual"]], key=lambda e: e["date"])
    years = sorted({e["year"] for e in ev})
    a_sav, c_sav = t1["A"]["savings"][0], t1["C"]["savings"][0]
    a_cap, c_cap = t1["A"]["capture"], t1["C"]["capture"]
    town = c["towns"]["Sterling"]
    cfg = s["source"]["config"]
    first = lambda v: v[0] if isinstance(v, list) else v  # noqa: E731
    aug_a = first(t1["A"]["aug"])
    d_a, d_b = first(t1["A"]["d_true"]), first(t1["B"]["d_true"])
    co2 = cfg["co2_kg_per_kwh"]
    lo = min(b["p50"] for b in r["bands"] if b["cond"] == "A") / cfg["e_nom_kwh"]
    lo_b = min(b["p50"] for b in r["bands"] if b["cond"] == "B") / cfg["e_nom_kwh"]
    rc = s["assumptions"]["retrofit_cost"]
    be = lambda tag: sens[tag]["prem_c"]  # noqa: E731
    last = annual[-1]
    rows = [("1-h battery", "duration_1h"), ("Failing cooling", "hvac_failing"), ("Cell faults", "fault_scenario"),
            ("Weak cooling", "hvac_weak"), ("4-h battery", "duration_4h"), ("2-h battery, LFP cells", "chem_LFP")]

    md = f"""# PeakSure demo video (website, about 3 minutes, after the pitch deck)

Generated by `tools/make_demo_script.py` from the data the website uses (model run {r['manifest']['finished']},
{r['manifest']['n_main']} paired runs per case). Re-run it after any model change. Show the site at full screen;
record voice over the screen. All figures are simulation results on real ISO-NE data.

## What to show (and what to skip)

Show: one real peak, one comparison, one lifetime view, one "where to deploy" view, the recommendation.
Skip: the scenario sliders, twin diagnostics, the old pages. Keep each number on screen while you say it.

## Script

**0:00–0:20 · Proposal tab (top).**
"PeakSure decides how much a battery should commit before each peak, using REON's cell-level data. We tested it on
every ISO-NE system peak from {years[0]} to {years[-1]}: {len(ev)} real peaks, with real hours and temperatures."

**0:20–1:05 · Compare tab, base case.** Click *Base case: {last['year']} annual peak*, press Play.
"This is the real annual peak on {last['date']}, hour ending {last['he']}, {last['t_amb_c']:.1f} °C. A 2.5 MW, 5 MWh plant:
on the left a conventional battery, on the right REON EBS with cell bypass, same cells, same weather.
Peak charges are real: transmission ${c['rns_2026']:.2f} per kW-year and capacity ${c['fca_kw_month']:.2f} per kW-month.
Shaving these peaks is worth about ${k(a_sav)} a year to the utility, roughly ${a_sav / town['customers']:,.0f} per customer
for a town Sterling's size ({town['customers']:,} customers)."
Then click *Drain test*, press Play, pause when the first fixed string stops.
"Run both to empty: the fixed string stops at its weakest cell and strands charge; REON switches that cell out and keeps going."

**1:05–1:35 · Reliability.** Point at the C card.
"With PeakSure's 95%-confidence commitment the battery covers {c_cap * 100:.0f}% of monthly peaks instead of {a_cap * 100:.0f}%.
It earns a little less (${k(c_sav)} vs ${k(a_sav)} a year) because it commits only what it is sure of, but it shows up when the peak arrives."

**1:35–2:10 · Compare tab, lifetime panel.** Scroll down.
"Over 15 years the conventional battery falls to {lo * 100:.0f}% of nameplate and needs {aug_a:,.0f} kWh of new cells;
REON EBS stays above {lo_b * 100:.0f}% and needs none. That is {d_b - d_a:,.0f} kWh more usable energy, about ${k(aug_a * cfg['augment_cost_kwh'], 1)}
of cells not bought and {aug_a * co2[1] / 1000:.1f} tonnes of manufacturing CO₂ avoided."

**2:10–2:40 · Proposal tab, where it pays.** Scroll to the cards.
"On a healthy 2-hour battery cell-level control adds almost nothing ({'−' if base_val < 0 else '+'}${abs(base_val) / 1000:.1f}K a year). It pays where cells
limit delivery: {', '.join(f'{n.lower()} +${k(val(t))}' for n, t in rows[:3])} a year. So we start there."

**2:40–3:00 · Recommendation.**
"Our plan: a read-only data pilot now, a retrofit on one or two struggling Massachusetts batteries next, then new
EBS systems once the field data confirms the value."

## Where the "where it pays" numbers come from

Each card is the extra annual peak saving from cell-level control: physical bypass value plus cell-twin value
(Shapley parts V1 + V2), averaged over 15 simulated years and {r['manifest']['n_side']} paired runs (base case
{r['manifest']['n_main']}), for a 2.5 MW plant on real ISO-NE peaks. One input changes per card:

| Card | What changes | Value per year | Break-even retrofit price (95% CI) |
|---|---|---|---|
| 2-h battery, healthy cells | base case | {'−' if base_val < 0 else '+'}${abs(base_val) / 1000:.1f}K | about $0/kWh |
""" + "\n".join(
        f"| {n} | {d} | +${k(val(t))} | ${be(t):,.0f}/kWh (${num(sens[t]['prem_c_lo'])}–{num(sens[t]['prem_c_hi'])}) |"
        for n, t, d in [(rows[0][0], rows[0][1], "5 MWh → 2.5 MWh"), (rows[1][0], rows[1][1], "no container cooling, ±6 °C cell spread"),
                        (rows[2][0], rows[2][1], "0.2% of cells fail per year"), (rows[3][0], rows[3][1], "cooling at 70% of outdoor swing, ±5 °C spread"),
                        (rows[4][0], rows[4][1], "5 MWh → 10 MWh"), (rows[5][0], rows[5][1], "LFP cells instead of sodium-ion")]) + f"""

**Break-even retrofit price** = the most a battery owner could pay per kWh for cell-level control and still come out
even over 15 years. Compare it with the retrofit estimate of ${rc['low']:.0f}–{rc['high']:.0f}/kWh: the 1-h, failing-cooling
and cell-fault cases clear it easily, weak cooling clears the middle of the range, a 4-h battery clears only the low end,
and a healthy 2-h battery does not. That ranking is the Stage 1 target list.
"""
    (ROOT / "DEMO_VIDEO.md").write_text(md)
    print("wrote DEMO_VIDEO.md")


if __name__ == "__main__":
    main()
