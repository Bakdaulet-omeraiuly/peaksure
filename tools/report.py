"""Generate RESULTS.md from results/ (every number in the report comes from the saved runs).

    python tools/report.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "app"))

import numpy as np
import pandas as pd

import analysis as an
from peaksure import econ
from peaksure.config import Config


def usd(x):
    return "n/a" if x != x else f"${x:,.0f}"


def ci(t):
    return f"{usd(t[0])} [{usd(t[1])}, {usd(t[2])}]"


def main() -> int:
    cfg = Config()
    man = an.manifest()
    ev, mo = an.load("events_main"), an.load("monthly_main")
    t1, rl = an.main_table(ev, mo, cfg, conds=("A", "B", "C", "D", "C_T3"))
    dec = econ.decomposition(rl)
    sens = an.sens_summary(an.load("events_sens"), an.load("monthly_sens"))
    cal = an.calib_summary(an.load("events_cal"))
    probe = an.probe_summary(an.load("events_probe"), an.load("monthly_probe"))
    names = {"A": "A Conventional", "B": "B REON bypass", "C": "C PeakSure", "D": "D PeakSure + VoI", "C_T3": "C + Tier 3"}

    L = []
    L.append("# PeakSure: Results\n")
    L.append(f"Generated by `tools/report.py` from `results/`. Config `{man.get('config_hash')}`, commit "
             f"`{man.get('git_commit')}`, {man.get('n_main')} paired runs per main condition, {man.get('n_side')} per "
             f"side study, {man.get('seconds')} s of compute. **Simulated ground truth, not hardware validation.** "
             "Independent analysis, not endorsed by REON.\n")
    L.append("System: REON CES 2.5 MW / 5 MWh (2 h), sodium-ion parameters, 15 years from 2027. Events are ISO-NE "
             "system monthly peaks 2019–2025 (bootstrapped by year), with WCMA temperatures. Rates: RNS and FCA (see the Addendum).\n")

    L.append("## T1. Main benchmark (mean [95% CI])\n")
    L.append("| Condition | Savings $/yr | NPV 15 yr | Peak capture | Delivered full | Annual peak | P5 miss | Cell-level premium $/kWh (same rule) |")
    L.append("|---|---|---|---|---|---|---|---|")
    for _, r in t1.iterrows():
        prem = "baseline" if r.cond == "A" else f"{r.premium_same[0]:,.1f} [{r.premium_same[1]:,.1f}, {r.premium_same[2]:,.1f}]"
        p5 = "n/a" if r.cond in ("A", "B") else f"{r.p5miss*100:.1f}% [{r.p5_lo*100:.1f}, {r.p5_hi*100:.1f}]"
        L.append(f"| {names[r.cond]} | {ci(r.savings)} | {ci(r.npv)} | {r.capture[0]*100:.1f}% | {r.delivered[0]*100:.1f}% | "
                 f"{r.annual[0]*100:.0f}% | {p5} | {prem} |")

    L.append("\n## T2. Value decomposition, 2-h CES ($/yr, paired, exact by construction)\n")
    L.append("| Component | Mean | 95% CI |")
    L.append("|---|---|---|")
    for _, r in dec.iterrows():
        L.append(f"| {r.component} | {usd(r['mean'])} | [{usd(r.lo)}, {usd(r.hi)}] |")

    if len(sens):
        L.append("\n## T3. Where it pays: one change at a time from base ($/yr; premium = paired NPV C minus A_opt per kWh)\n")
        L.append("| Scenario | Physical V1 | Informational V2 | V1+V2 | Decision rule | Premium $/kWh [95% CI] |")
        L.append("|---|---|---|---|---|---|")
        for _, r in sens.sort_values("prem_c", ascending=False).iterrows():
            L.append(f"| {r.tag} | {usd(r.v1)} | {usd(r.v2)} | {usd(r.v1 + r.v2)} | {usd(r.rule)} | "
                     f"{r.prem_c:,.1f} [{r.prem_c_lo:,.1f}, {r.prem_c_hi:,.1f}] |")

    if len(cal):
        L.append("\n## T4. Twin calibration: share of peaks where true energy < predicted P5 (target 5%)\n")
        L.append("| Mismatch | eps | Pack-level | Cell twin |")
        L.append("|---|---|---|---|")
        for (mode, eps), g in cal.groupby(["mode", "eps"]):
            a = g[g.cond == "A_opt"].iloc[0]
            c = g[g.cond == "C"].iloc[0]
            L.append(f"| {'systematic' if mode == 'sys' else 'random'} | {eps:.1f} | {a.miss*100:.1f}% [{a.lo*100:.1f}, {a.hi*100:.1f}] "
                     f"(width {a.width*100:.1f}%) | {c.miss*100:.1f}% [{c.lo*100:.1f}, {c.hi*100:.1f}] (width {c.width*100:.1f}%) |")

    if len(probe) and "gain" in probe:
        L.append("\n## T5. VoI probing on a 4-h system: extra savings vs no probing ($/yr, paired)\n")
        L.append("| Policy | Budget | Probes used / peak | Gain [95% CI] |")
        L.append("|---|---|---|---|")
        for _, r in probe.sort_values(["budget", "cond"]).iterrows():
            b = "-" if r.budget != r.budget else int(r.budget)
            L.append(f"| {r.cond} ({r.tag}) | {b} | {r.probes:.2f} | {usd(r.gain)} [{usd(r.gain_lo)}, {usd(r.gain_hi)}] |")

    L.append("\n## Reading the results\n")
    v12 = dec.set_index("component")["mean"]
    L.append(f"- At the CES's 2-h duration, V1 + V2 = {usd(v12['V1 Physical (bypass)'] + v12['V2 Informational (cell twin)'])}/yr. "
             "Energy rarely limits the coincident-peak decision; peak-hour timing dominates.")
    if len(sens):
        s = sens.set_index("tag")
        for tag in ("duration_1h", "duration_3h", "duration_4h"):
            if tag in s.index:
                r = s.loc[tag]
                L.append(f"- {tag}: V1 + V2 = {usd(r.v1 + r.v2)}/yr, premium {r.prem_c:,.1f} $/kWh "
                         f"[{r.prem_c_lo:,.1f}, {r.prem_c_hi:,.1f}].")
    L.append("- The decision-rule component is reported separately and is not credited to REON's hardware.")
    L.append("- Probing results include the null and negative cases; PeakSure's VoI policy may decline to probe.")
    (ROOT / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("wrote RESULTS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
